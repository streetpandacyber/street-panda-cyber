/* ────────────────────────────── HELPERS ─────────────────────────── */

export function productRatingBreakdown(count = 120) {
  const five = Math.round(count * 0.78);
  const four = Math.round(count * 0.16);
  const three = Math.round(count * 0.04);
  const two = Math.round(count * 0.01);
  const one = Math.max(0, count - five - four - three - two);
  return [
    { stars: 5, count: five },
    { stars: 4, count: four },
    { stars: 3, count: three },
    { stars: 2, count: two },
    { stars: 1, count: one },
  ];
}
