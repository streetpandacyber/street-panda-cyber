Tell the model who to be. *Act as a senior marketing consultant with ten years of experience in East African retail.* A role changes the vocabulary, the depth and the confidence of the answer. Without a role, you get the model's average of the internet, which is exactly what your competitors get.

## Part 2: Context

Hand over the real facts. *I run a small clothing business in Nairobi with 3,000 Instagram followers and a KES 20,000 monthly ad budget.* AI cannot read your mind, and every sentence of context you add removes a guess from its answer. Beginners skip context and then blame the tool.

## Part 3: Task

Say exactly what you want, as one clear verb phrase. *Write a 30-day launch plan.* Not *help me with my business*, which is a fog, not a task. If you cannot state the task in one sentence, the model cannot execute it in one answer.

## Part 4: Format

Describe the shape of the answer. *Present it as a table with columns: week, action, cost, expected result.* Format instructions are the most underrated lever in prompting, because they force the model to organise its thinking before it writes, and organised thinking reads as quality.

## Part 5: Constraint

Set a limit. *Keep each action under KES 5,000 and assume I have no design skills.* Constraints cut the generic filler out of an answer. An AI with boundaries produces specifics; an AI without them produces advice you have heard a hundred times.

